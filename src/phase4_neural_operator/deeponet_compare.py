"""
deeponet_compare.py

Purpose: Before/after comparison for the DeepONet fixes. Trains each
recipe in train_deeponet.CONFIGS (seed 0) into models/candidates/, then
evaluates those and a baseline model file with deeponet_evaluate.py's exact
metrics. Writes results/deeponet_before_after.json and .md.

The baseline defaults to the DeepONet that was deployed before these fixes.
That file is in git history; to re-create it locally:
    git show 341df20:models/deeponet_diffusion.pt > models/candidates/deployed_before.pt

Run (from the project root):
    python src/phase4_neural_operator/deeponet_compare.py
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from deeponet_evaluate import evaluate  # noqa: E402
from deeponet_model import load_deeponet  # noqa: E402
from train_deeponet import CONFIGS, train_deeponet  # noqa: E402

CANDIDATE_DIR = "models/candidates"
OUT_JSON = "results/deeponet_before_after.json"
OUT_MD = "results/deeponet_before_after.md"


def summarize(name, res, recipe, timings=None):
    i, e, b = res["interpolation"], res["extrapolation"], res["app_curve_bounds"]
    return {
        "model": name,
        "recipe": recipe,
        "timings_seconds": timings,
        "interp_mae": i["mae"], "interp_rel_l2": i["rel_l2"], "interp_r2": i["r2"],
        "interp_worst_D_mae": i["worst_D_mae"],
        "interp_mae_D_0.012": i["per_D"]["0.012"]["mae"],
        "extrap_mae": e["mae"], "extrap_rel_l2": e["rel_l2"], "extrap_worst_D_mae": e["worst_D_mae"],
        "app_curve_frac_below_0": b["frac_below_0"], "app_curve_frac_above_1": b["frac_above_1"],
        "app_curve_worst_violation": b["worst_violation"],
        "grid_worst_violation": max(i["bounds_on_grid"]["worst_violation"],
                                    e["bounds_on_grid"]["worst_violation"]),
        "full": res,
    }


def to_markdown(rows):
    cols = [
        ("Model", lambda r: r["model"]),
        ("Interp MAE", lambda r: f"{r['interp_mae']:.4f}"),
        ("Interp rel L2", lambda r: f"{r['interp_rel_l2']:.4f}"),
        ("Interp worst-D MAE", lambda r: f"{r['interp_worst_D_mae']:.4f}"),
        ("MAE at D=0.012", lambda r: f"{r['interp_mae_D_0.012']:.4f}"),
        ("Extrap MAE", lambda r: f"{r['extrap_mae']:.4f}"),
        ("Extrap worst-D MAE", lambda r: f"{r['extrap_worst_D_mae']:.4f}"),
        ("App curve <0 / >1", lambda r: f"{100 * r['app_curve_frac_below_0']:.1f}% / {100 * r['app_curve_frac_above_1']:.1f}%"),
        ("App curve worst violation", lambda r: f"{r['app_curve_worst_violation']:.3f}"),
        ("Train time (s)", lambda r: f"{r['timings_seconds']['training_seconds']:.0f}" if r["timings_seconds"] else "n/a"),
    ]
    lines = ["| " + " | ".join(c for c, _ in cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(f(r) for _, f in cols) + " |" for r in rows]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--baseline", default=os.path.join(CANDIDATE_DIR, "deployed_before.pt"))
    parser.add_argument("--configs", nargs="*", default=list(CONFIGS))
    args = parser.parse_args()

    os.makedirs(CANDIDATE_DIR, exist_ok=True)
    rows = []
    if os.path.exists(args.baseline):
        res = evaluate(load_deeponet(args.baseline))
        rows.append(summarize("deployed before (commit 341df20)", res, "unknown: weights only"))

    for name in args.configs:
        path = os.path.join(CANDIDATE_DIR, f"{name}.pt")
        print(f"\n### training '{name}': {CONFIGS[name]}")
        model, timings = train_deeponet(**CONFIGS[name], seed=0, model_out=path, verbose=True)
        rows.append(summarize(name, evaluate(model), {**CONFIGS[name], "seed": 0}, timings))

    md = to_markdown(rows)
    print("\n" + md)
    with open(OUT_JSON, "w") as f:
        json.dump(rows, f, indent=2)
    with open(OUT_MD, "w", encoding="utf-8") as f:
        f.write("# DeepONet before/after (held-out D, corner excluded)\n\n"
                "Generated by `src/phase4_neural_operator/deeponet_compare.py`. Interp = 12 D values "
                "inside [0.01, 1.0]; extrap = 0.003, 0.005, 0.0075, 1.25, 1.5, 2.0. Metrics are "
                "against the exact solution on a 51 x 51 (x, t) grid. 'App curve' = what the app "
                "plots (x = 0.5, t in [0, 5], every slider D).\n\n")
        f.write(md + "\n")
    print(f"\nSaved {OUT_JSON} and {OUT_MD}")


if __name__ == "__main__":
    main()
